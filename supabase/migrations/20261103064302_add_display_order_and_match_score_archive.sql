/*
# Add display order to lists and score/archive fields to matches

Plain-English summary:
Admins can now drag items into any order in the news, roster, gallery, merch,
matches lists. Matches also get a score, a best-of format and an archive flag.
Existing rows keep all their data; their current order is preserved.

## 1. Modified tables
- `news`, `players`, `gallery_photos`, `merch_products`, `matches`:
  - `position` (integer, auto-numbered identity column) - display order.
    Existing rows are numbered once to match their current order on the site
    (news by date, newest first; other lists by creation time).
- `matches`:
  - `is_archived` (boolean, default false) - archived matches are hidden from
    the active list on the site.
  - `team_score` and `opponent_score` (integer, nullable) - rounds or maps won.
  - `match_format` (text, default 'bo1', one of bo1 / bo3 / bo5).

## 2. Security
- No change to row level security or grants; the new columns follow the
  existing table policies.

## 3. Important notes
1. The numbering runs only the first time this migration is applied, so
   re-running it never reorders lists the admin has already arranged.
2. No existing columns or rows are removed or changed.
*/

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'matches' AND column_name = 'position'
  ) THEN
    ALTER TABLE matches ADD COLUMN position integer GENERATED BY DEFAULT AS IDENTITY;
    ALTER TABLE players ADD COLUMN position integer GENERATED BY DEFAULT AS IDENTITY;
    ALTER TABLE gallery_photos ADD COLUMN position integer GENERATED BY DEFAULT AS IDENTITY;
    ALTER TABLE merch_products ADD COLUMN position integer GENERATED BY DEFAULT AS IDENTITY;
    ALTER TABLE news ADD COLUMN position integer GENERATED BY DEFAULT AS IDENTITY;

    UPDATE matches m SET position = r.rn
    FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) AS rn FROM matches) r
    WHERE m.id = r.id;

    UPDATE players p SET position = r.rn
    FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) AS rn FROM players) r
    WHERE p.id = r.id;

    UPDATE gallery_photos g SET position = r.rn
    FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) AS rn FROM gallery_photos) r
    WHERE g.id = r.id;

    UPDATE merch_products mp SET position = r.rn
    FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) AS rn FROM merch_products) r
    WHERE mp.id = r.id;

    UPDATE news n SET position = r.rn
    FROM (SELECT id, row_number() OVER (ORDER BY date DESC, created_at DESC, id) AS rn FROM news) r
    WHERE n.id = r.id;

    PERFORM setval(pg_get_serial_sequence('matches', 'position'), GREATEST((SELECT COALESCE(MAX(position), 1) FROM matches), 1));
    PERFORM setval(pg_get_serial_sequence('players', 'position'), GREATEST((SELECT COALESCE(MAX(position), 1) FROM players), 1));
    PERFORM setval(pg_get_serial_sequence('gallery_photos', 'position'), GREATEST((SELECT COALESCE(MAX(position), 1) FROM gallery_photos), 1));
    PERFORM setval(pg_get_serial_sequence('merch_products', 'position'), GREATEST((SELECT COALESCE(MAX(position), 1) FROM merch_products), 1));
    PERFORM setval(pg_get_serial_sequence('news', 'position'), GREATEST((SELECT COALESCE(MAX(position), 1) FROM news), 1));
  END IF;
END $$;

ALTER TABLE matches ADD COLUMN IF NOT EXISTS is_archived boolean NOT NULL DEFAULT false;
ALTER TABLE matches ADD COLUMN IF NOT EXISTS team_score integer CHECK (team_score IS NULL OR team_score >= 0);
ALTER TABLE matches ADD COLUMN IF NOT EXISTS opponent_score integer CHECK (opponent_score IS NULL OR opponent_score >= 0);
ALTER TABLE matches ADD COLUMN IF NOT EXISTS match_format text NOT NULL DEFAULT 'bo1' CHECK (match_format IN ('bo1', 'bo3', 'bo5'));
